"""
What: Per-site summary, sanity check and Markdown text of the stage 2 report. Pure functions.
Roadmap stage: 2 — Horizon (see docs/ROTEIRO.md)
Inputs: HorizonResult per site, observer heights (m), DEM layout and bands.
Outputs: SiteSummary records and the text of data/horizon/REPORT.md.
NASA data source: horizons derived from the LOLA DEM, PGDA product 90.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from pipeline import config
from pipeline.horizon.dem_cog import CogDem
from pipeline.horizon.geometry import smooth_sphere_dip_deg
from pipeline.horizon.horizon_profile import Band, HorizonResult

M_PER_KM = 1000.0
# A contour whose range is below this is treated as constant (suspicious), degrees.
CONSTANT_RANGE_DEG = 1e-6


@dataclass(frozen=True)
class SiteSummary:
    """Summary of one site's horizon. Angles in degrees, distances in km, heights in m."""

    site_id: str
    terrain_m: float
    slope_deg: float
    mast_m: float
    min_deg: float
    max_deg: float
    mean_deg: float
    max_azimuth_deg: int
    max_distance_km: float
    dip_observer_deg: float
    dip_mast_only_deg: float
    cut_fraction: float
    cut_min_km: float
    cut_max_km: float
    missing_bins: int
    sane: bool
    sanity_message: str


def summarize(
    site_id: str,
    terrain_m: float,
    slope: float,
    mast_m: float,
    radius_m: float,
    result: HorizonResult,
) -> SiteSummary:
    """Summary and sanity verdict of one horizon (range -10..35 deg, not constant, complete)."""
    el = result.elevation_deg
    finite = np.isfinite(el)
    k = int(np.nanargmax(el)) if finite.any() else 0
    cut = result.cut_distance_m
    cut_bins = np.isfinite(cut)
    problems = []
    if not finite.all():
        problems.append(f"{int((~finite).sum())} azimuth bins without data")
    if finite.any() and (
        np.nanmin(el) < config.HORIZON_SANITY_MIN_DEG
        or np.nanmax(el) > config.HORIZON_SANITY_MAX_DEG
    ):
        problems.append(
            f"contour {np.nanmin(el):.2f}..{np.nanmax(el):.2f} deg outside "
            f"[{config.HORIZON_SANITY_MIN_DEG}, {config.HORIZON_SANITY_MAX_DEG}]"
        )
    if finite.any() and np.nanmax(el) - np.nanmin(el) < CONSTANT_RANGE_DEG:
        problems.append("contour is constant")
    return SiteSummary(
        site_id=site_id,
        terrain_m=terrain_m,
        slope_deg=slope,
        mast_m=mast_m,
        min_deg=float(np.nanmin(el)),
        max_deg=float(np.nanmax(el)),
        mean_deg=float(np.nanmean(el)),
        max_azimuth_deg=k,
        max_distance_km=float(result.obstacle_distance_m[k] / M_PER_KM),
        dip_observer_deg=smooth_sphere_dip_deg(terrain_m + mast_m, radius_m),
        dip_mast_only_deg=smooth_sphere_dip_deg(mast_m, radius_m),
        cut_fraction=float(cut_bins.mean()),
        cut_min_km=float(np.min(cut[cut_bins]) / M_PER_KM) if cut_bins.any() else float("nan"),
        cut_max_km=float(np.max(cut[cut_bins]) / M_PER_KM) if cut_bins.any() else float("nan"),
        missing_bins=int((~finite).sum()),
        sane=not problems,
        sanity_message="; ".join(problems) if problems else "OK",
    )


def render_report(
    summaries: list[SiteSummary],
    bands: list[Band],
    dem: CogDem,
    mast_m: float,
    fine_step_deg: float,
) -> str:
    """Markdown text of the stage 2 report."""
    band_text = ", ".join(
        f"{b.step_m:g} m pixels up to {b.max_distance_m / M_PER_KM:g} km" for b in bands
    )
    lines = [
        "# Stage 2 - Terrain horizon report",
        "",
        "Generated by `python -m pipeline.horizon.run_horizon`. Do not edit by hand.",
        "",
        f"- DEM: {config.HORIZON_DEM_PRODUCT}, read by HTTP range from {dem.url}",
        f"- Heights: metres above a sphere of {dem.sphere_radius_m / M_PER_KM:g} km "
        "(datum declared in the file).",
        f"- Sampling: {band_text}; fine azimuth step {fine_step_deg:g} deg, maximum kept per "
        "whole-degree bin [i - 0.5, i + 0.5).",
        f"- Observer: DEM terrain height (20 m grid, bilinear) + {mast_m:g} m mast (team choice).",
        "- Elevations: 3D vectors on a sphere, not clamped at 0. Azimuth as JPL Horizons "
        "(N=0, E=90, clockwise).",
        "- Edge rule: a ray stops where it leaves the DEM; terrain beyond is treated as unknown.",
        f"- Sanity: contour must stay within [{config.HORIZON_SANITY_MIN_DEG:g}, "
        f"{config.HORIZON_SANITY_MAX_DEG:g}] deg and must not be constant.",
        "",
        "## Contour (degrees)",
        "",
        "| Site | Terrain h (m) | Slope (deg) | Min | Max | Mean | Highest obstacle: azimuth "
        "| distance (km) | Sanity |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for s in summaries:
        lines.append(
            f"| {s.site_id} | {s.terrain_m:.1f} | {s.slope_deg:.1f} | {s.min_deg:.3f} | "
            f"{s.max_deg:.3f} | "
            f"{s.mean_deg:.3f} | {s.max_azimuth_deg} | {s.max_distance_km:.2f} | "
            f"{s.sanity_message} |"
        )
    lines += [
        "",
        "## Smooth-sphere horizon dip (for comparison)",
        "",
        'Dip = -acos(R / (R + h)). "Observer height" uses h = terrain height above the '
        f'sphere + mast; "mast only" uses h = {mast_m:g} m above a locally smooth surface.',
        "",
        "| Site | Observer height above sphere (m) | Dip, observer height (deg) "
        "| Dip, mast only (deg) | Min of computed contour (deg) |",
        "|---|---|---|---|---|",
    ]
    for s in summaries:
        lines.append(
            f"| {s.site_id} | {s.terrain_m + s.mast_m:.1f} | {s.dip_observer_deg:.3f} | "
            f"{s.dip_mast_only_deg:.4f} | {s.min_deg:.3f} |"
        )
    lines += [
        "",
        "## DEM edge",
        "",
        "Fraction of the 360 whole-degree bins in which at least one ray left the DEM before "
        "the search radius, and the distances at which those rays were cut.",
        "",
        "| Site | Bins cut | Fraction | Cut distance min (km) | Cut distance max (km) |",
        "|---|---|---|---|---|",
    ]
    for s in summaries:
        n_cut = round(s.cut_fraction * 360)
        rng = f"{s.cut_min_km:.1f} | {s.cut_max_km:.1f}" if n_cut else "- | -"
        lines.append(f"| {s.site_id} | {n_cut} | {s.cut_fraction:.1%} | {rng} |")
    lines += [
        "",
        "Per-degree cut distances are in `data/horizon/<id>.json` (`cut_distance_km`).",
        "",
        "## Summary",
        "",
        "All sanity checks passed."
        if all(s.sane for s in summaries)
        else "**Some sanity checks FAILED.**",
        "",
    ]
    return "\n".join(lines)

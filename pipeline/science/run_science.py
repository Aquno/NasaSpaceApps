"""
What: Orchestrate stage 3: distance from each site to the nearest permanently shadowed region
    (PSR) of at least 1 km2, with that PSR's area and identifier; write JSON and report.
Roadmap stage: 3 — Science value (see docs/ROTEIRO.md)
Inputs: pipeline/sites.json; PGDA product 90 PSR shapefile (> 1 km2), cached in
    data/raw/pgda90/psr/.
Outputs: data/science/psr_distance.json; data/science/REPORT.md.
NASA data source: PGDA product 90 (https://pgda.gsfc.nasa.gov/products/90).

Proximity to permanent shadow as a science indicator and the 1 km2 bound are team choices
(docs/DECISOES.md D21), not NASA criteria.

Usage: python -m pipeline.science.run_science
"""

from __future__ import annotations

import json
import sys

import numpy as np

from pipeline import config
from pipeline.horizon.geometry import unit_vector
from pipeline.science.psr_distance import nearest_psr
from pipeline.science.psr_files import download_if_missing, load_psr_polygons
from pipeline.sites.polar_stereo import forward_south_polar, inverse_south_polar
from pipeline.sites.site_list import load_sites

M_PER_KM = 1000.0
EXIT_CHECK_FAILED = 2


def great_circle_m(lat1: float, lon1: float, lat2: float, lon2: float, radius_m: float) -> float:
    """Great-circle distance in metres between two points (degrees) on a sphere."""
    cosang = float(np.clip(unit_vector(lat1, lon1) @ unit_vector(lat2, lon2), -1.0, 1.0))
    return radius_m * float(np.arccos(cosang))


def main() -> int:
    """Command-line entry point. Returns the process exit code."""
    import truststore

    truststore.inject_into_ssl()  # use the OS certificate store (see requirements.txt)
    raw = config.RAW_DIR / "pgda90" / "psr"
    shp = download_if_missing(f"{config.PSR_BASE_URL}.SHP", raw / "LPSR_80S_20MPP_ADJ_1km2.SHP")
    dbf = download_if_missing(f"{config.PSR_BASE_URL}.DBF", raw / "LPSR_80S_20MPP_ADJ_1km2.DBF")
    polygons = [p for p in load_psr_polygons(shp, dbf) if p.area_km2 >= config.PSR_MIN_AREA_KM2]
    radius_m = config.LUNAR_SPHERE_RADIUS_KM * M_PER_KM

    results, problems = [], []
    for site in load_sites(config.SITES_FILE):
        x, y = forward_south_polar(site.lat, site.lon, radius_m)
        near = nearest_psr(x, y, polygons)
        psr = polygons[near.index]
        lat_b, lon_b = inverse_south_polar(*near.nearest_xy_m, radius_m)
        distance_m = (
            0.0 if near.inside else great_circle_m(site.lat, site.lon, lat_b, lon_b, radius_m)
        )
        results.append(
            {
                "site_id": site.id,
                "psr_distance_km": round(distance_m / M_PER_KM, 3),
                "inside_psr": near.inside,
                "planar_distance_km": round(near.planar_distance_m / M_PER_KM, 3),
                "nearest_boundary_lat": round(lat_b, 6),
                "nearest_boundary_lon": round(lon_b, 6),
                "psr_gid": psr.gid,
                "psr_name": psr.name,
                "psr_area_km2": psr.area_km2,
            }
        )
        if not np.isfinite(distance_m) or distance_m < 0:
            problems.append(f"{site.id}: invalid distance {distance_m}")
        if abs(distance_m - near.planar_distance_m) > 0.01 * max(near.planar_distance_m, 1.0):
            problems.append(f"{site.id}: sphere vs plane distance differ by more than 1%")

    out = {
        "meta": {
            "product": config.PSR_PRODUCT,
            "files": [f"{config.PSR_BASE_URL}.SHP", f"{config.PSR_BASE_URL}.DBF"],
            "psr_count": len(polygons),
            "min_area_km2": config.PSR_MIN_AREA_KM2,
            "distance": (
                "great-circle distance on the 1737.4 km sphere from the site to the nearest "
                "point of the nearest PSR boundary (nearest point found on the polar "
                "stereographic plane); 0 if the site is inside a PSR"
            ),
            "indicator_note": (
                "proximity to permanent shadow as a science indicator and the 1 km2 bound "
                "are team choices, not NASA criteria"
            ),
        },
        "sites": results,
    }
    config.SCIENCE_DIR.mkdir(parents=True, exist_ok=True)
    (config.SCIENCE_DIR / "psr_distance.json").write_text(
        json.dumps(out, indent=1), encoding="utf-8"
    )
    report = render_report(results, len(polygons), problems)
    (config.SCIENCE_DIR / "REPORT.md").write_text(report, encoding="utf-8")
    print(report)
    return EXIT_CHECK_FAILED if problems else 0


def render_report(results: list[dict], psr_count: int, problems: list[str]) -> str:
    """Markdown text of the stage 3 report."""
    lines = [
        "# Stage 3 - Science value report",
        "",
        "Generated by `python -m pipeline.science.run_science`. Do not edit by hand.",
        "",
        f"- Source: {config.PSR_PRODUCT}; {psr_count} PSR polygons used "
        f"(area >= {config.PSR_MIN_AREA_KM2:g} km2).",
        "- Distance: from the site to the boundary of the nearest PSR, great-circle on the "
        "1737.4 km sphere; 0 if inside.",
        "- Team choices (not NASA criteria): proximity to permanent shadow as a science "
        "indicator; the 1 km2 bound.",
        "",
        "| Site | Distance to nearest PSR (km) | Inside? | PSR name (as published) "
        "| PSR gid | PSR area (km2) |",
        "|---|---|---|---|---|---|",
    ]
    for r in results:
        lines.append(
            f"| {r['site_id']} | {r['psr_distance_km']:.3f} | "
            f"{'yes' if r['inside_psr'] else 'no'} | "
            f"{r['psr_name']} | {r['psr_gid']} | {r['psr_area_km2']:.3f} |"
        )
    lines += ["", "## Summary", ""]
    lines.append("All checks passed." if not problems else "**Problems:** " + "; ".join(problems))
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    sys.exit(main())
